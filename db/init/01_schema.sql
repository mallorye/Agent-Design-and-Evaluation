/* =============================================================================
   Advancement — Synthetic Dataset DDL
   -----------------------------------------------------------------------------
   Context : PostgreSQL 15+ (NULLS NOT DISTINCT in contact_preference needs 15;
             a fallback for older versions is noted at that index).
             Tested on PostgreSQL 16.
   Purpose : Five normalized base tables modeled on common Advancement data needs.
   Tables  : designation              (lookup)
             constituent              (hub)
             contribution             (fact; FKs to constituent + designation)
             contact_preference       (1:N from constituent)
             constituent_relationship (self-referencing M:N on constituent)
   
   ============================================================================= */

DROP SCHEMA IF EXISTS synth_advancement CASCADE;
CREATE SCHEMA synth_advancement;
SET search_path TO synth_advancement;




/* -----------------------------------------------------------------------------
   designation — one row per fund
   Natural key: codes look numeric but are identifiers (no math, may need
   leading zeros), so they are stored as text with a format check.
   ----------------------------------------------------------------------------- */
CREATE TABLE designation (
    designation_code    TEXT            NOT NULL,
    designation_name        text   NOT NULL,
    division            text   NOT NULL,   -- college/school or unit
    department          text,              -- NULL = division-level fund
    is_active           BOOLEAN         NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_designation
        PRIMARY KEY (designation_code),
    CONSTRAINT ck_designation_code_format
        CHECK (designation_code ~ '^\d{8}$')
);


/* -----------------------------------------------------------------------------
   constituent — one row per person or organization
   Spouse is NOT stored here; it lives only in constituent_relationship so
   there is a single source of truth (the warehouse stores it in both places).
   Address completeness is deliberately NOT enforced: incomplete addresses are
   realistic and are exactly what the mailable logic filters out.
   ----------------------------------------------------------------------------- */
CREATE TABLE constituent (
    constituent_id       INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    entity_type          CHAR(1)         NOT NULL DEFAULT 'P',   -- P = person, C = organization
    first_name           text,
    preferred_name       text,
    last_name            text,
    org_name             text,
    primary_affiliation  text   NOT NULL,
    email                text,
    address_line1        text,
    address_city         text,
    address_state        CHAR(2),
    address_postal_code  text,
    address_country      text   NOT NULL DEFAULT 'United States',
    constituent_status   text   NOT NULL DEFAULT 'Active',
    is_deceased          BOOLEAN         NOT NULL DEFAULT FALSE,
    deceased_date        DATE,           -- typed DATE: no unparseable text dates

    CONSTRAINT pk_constituent
        PRIMARY KEY (constituent_id),
    CONSTRAINT ck_constituent_entity_type
        CHECK (entity_type IN ('P', 'C')),
    -- People need a last name and no org name; orgs need an org name and no person names
    CONSTRAINT ck_constituent_name_by_type
        CHECK (
               (entity_type = 'P' AND last_name IS NOT NULL AND org_name IS NULL)
            OR (entity_type = 'C' AND org_name IS NOT NULL
                                  AND first_name IS NULL
                                  AND preferred_name IS NULL
                                  AND last_name IS NULL)
        ),
    CONSTRAINT ck_constituent_affiliation
        CHECK (primary_affiliation IN (
            'Alumnus/Alumna', 'Parent', 'Friend', 'Faculty/Staff',
            'Student', 'Trustee', 'Corporation', 'Foundation'
        )),
    CONSTRAINT ck_constituent_status
        CHECK (constituent_status IN ('Active', 'Inactive')),
   
    -- Organizations cannot be deceased
    CONSTRAINT ck_constituent_deceased_person_only
        CHECK (entity_type = 'P' OR is_deceased = FALSE),
    -- A deceased date implies deceased (deceased with unknown date is allowed)
    CONSTRAINT ck_constituent_deceased_date
        CHECK (deceased_date IS NULL OR is_deceased = TRUE)
);


/* -----------------------------------------------------------------------------
   contribution — one row per gift, pledge, matching gift, or bequest expectancy
   fiscal_year is a stored generated column (synth FY runs Jul 1 – Jun 30), the
   Postgres analogue of dbo.fn_GetFiscalYear().
   ON DELETE RESTRICT on both FKs: giving history should never disappear
   because a constituent or fund row was deleted.
   ----------------------------------------------------------------------------- */
CREATE TABLE contribution (
    contribution_id      INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    constituent_id       INTEGER         NOT NULL,
    credit               VARCHAR         NOT NULL,
    designation_code     TEXT            NOT NULL,
    contribution_date    DATE            NOT NULL,
    fiscal_year          INTEGER         GENERATED ALWAYS AS (
                             EXTRACT(YEAR FROM contribution_date)::INTEGER
                             + CASE WHEN EXTRACT(MONTH FROM contribution_date) >= 7
                                    THEN 1 ELSE 0 END
                         ) STORED,
    contribution_type    text   NOT NULL,
    amount               NUMERIC(12,2)   NOT NULL,
    pledge_status        text,
    payment_type         text,
    is_anonymous         BOOLEAN         NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_contribution
        PRIMARY KEY (contribution_id),
    CONSTRAINT fk_contribution_constituent
        FOREIGN KEY (constituent_id)
        REFERENCES constituent (constituent_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_contribution_designation
        FOREIGN KEY (designation_code)
        REFERENCES designation (designation_code)
        ON DELETE RESTRICT,
    CONSTRAINT ck_contribution_amount_positive
        CHECK (amount > 0),
    CONSTRAINT ck_contribution_type
        CHECK (contribution_type IN ('Gift', 'Pledge', 'Matching Gift', 'Bequest Expectancy', 'Pledge Payment','Bequest Expectancy Payment', 'Matching Gift Payment')),
    CONSTRAINT ck_contribution_pledge_status
        CHECK (pledge_status IN ('Open', 'Paid', 'Canceled', 'Written Off')),
    -- Pledge fields only make sense on pledge-like commitments
    CONSTRAINT ck_contribution_pledge_fields_scope
        CHECK (contribution_type IN ('Pledge', 'Bequest Expectancy')
               OR (pledge_status IS NULL )),
    -- Every pledge carries a status
    CONSTRAINT ck_contribution_pledge_has_status
        CHECK (contribution_type <> 'Pledge' OR pledge_status IS NOT NULL),
    CONSTRAINT credit_type
        CHECK(credit = 'Hard' OR credit = 'Soft'),
    CONSTRAINT ck_contribution_payment_type
        CHECK (payment_type IN ('Cash', 'Check', 'Credit Card', 'ACH', 'Securities', 'Gift-in-kind'))
);


/* -----------------------------------------------------------------------------
   contact_preference — one row per contact restriction
   department NULL = university-wide restriction.
   end_date NULL = open-ended (still in effect).
   ON DELETE CASCADE: a preference has no meaning without its constituent.
   ----------------------------------------------------------------------------- */
CREATE TABLE contact_preference (
    contact_preference_id  INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    constituent_id         INTEGER        NOT NULL,
    preference_type        text  NOT NULL,
    restriction_type       text  NOT NULL,
    contact_method         text  NOT NULL,
    department             text,
    end_date               DATE,

    CONSTRAINT pk_contact_preference
        PRIMARY KEY (contact_preference_id),
    CONSTRAINT fk_contact_preference_constituent
        FOREIGN KEY (constituent_id)
        REFERENCES constituent (constituent_id)
        ON DELETE CASCADE,
    CONSTRAINT ck_contact_preference_type
        CHECK (preference_type IN ('Communication', 'Solicitations', 'Event Invitations')),
    CONSTRAINT ck_contact_preference_restriction
        CHECK (restriction_type IN ('Exclude', 'No Reconnect', 'Include')),
    CONSTRAINT ck_contact_preference_method
        CHECK (contact_method IN ('All', 'Email', 'Letter'))
    
);

-- At most one open-ended restriction per constituent / type / method / department.
-- restriction_type is intentionally NOT in the key, so an open 'Exclude' and an
-- open 'Include' for the same slot cannot coexist.
-- NULLS NOT DISTINCT (PG15+) makes two university-wide rows (department IS NULL)
-- count as duplicates; by default Postgres treats NULLs as distinct and allows them.
-- Pre-15 fallback: replace department with COALESCE(department, '(university-wide)')
-- in the column list and drop the NULLS NOT DISTINCT clause.
CREATE UNIQUE INDEX ux_contact_preference_open
    ON contact_preference (constituent_id, preference_type, contact_method, department)
    NULLS NOT DISTINCT
    WHERE end_date IS NULL;


/* -----------------------------------------------------------------------------
   constituent_relationship — one row per pair of related people
   Mirrors PersonalRelationship: each side carries its own role
   (person2_role = 'Parent' means person2 is the parent).
   Canonical ordering (person1_id < person2_id) stores each pair exactly once,
   so (A,B) and (B,A) cannot both exist, which is one source of the duplicate
   rows the warehouse forces you to DISTINCT away.
   No deceased flag here: derive it by joining to constituent.
   ON DELETE CASCADE: a relationship has no meaning without both people.
   ----------------------------------------------------------------------------- */
CREATE TABLE constituent_relationship (
    person1_id     INTEGER        NOT NULL,
    person1_role   text  NOT NULL,
    person2_id     INTEGER        NOT NULL,
    person2_role   text  NOT NULL,

    CONSTRAINT pk_constituent_relationship
        PRIMARY KEY (person1_id, person2_id),
    CONSTRAINT fk_constituent_relationship_person1
        FOREIGN KEY (person1_id)
        REFERENCES constituent (constituent_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_constituent_relationship_person2
        FOREIGN KEY (person2_id)
        REFERENCES constituent (constituent_id)
        ON DELETE CASCADE,
    CONSTRAINT ck_constituent_relationship_canonical_order
        CHECK (person1_id < person2_id),
    -- Roles must be reciprocal
    CONSTRAINT ck_constituent_relationship_role_pair
        CHECK ((person1_role, person2_role) IN (
            ('Spouse',       'Spouse'),
            ('Life Partner', 'Life Partner'),
            ('Parent',       'Child'),
            ('Child',        'Parent'),
            ('Grandparent',  'Grandchild'),
            ('Grandchild',   'Grandparent'),
            ('Sibling',      'Sibling')
        ))
);


/* -----------------------------------------------------------------------------
   INDEXES
   Postgres does NOT auto-index foreign key columns (SQL Server doesn't either).
   constituent_relationship.person1_id is already covered as the leading column
   of its primary key.
   ----------------------------------------------------------------------------- */
CREATE INDEX ix_contribution_constituent        ON contribution (constituent_id);
CREATE INDEX ix_contribution_designation        ON contribution (designation_code);
CREATE INDEX ix_contribution_fiscal_year        ON contribution (fiscal_year);
CREATE INDEX ix_contact_preference_constituent  ON contact_preference (constituent_id);
CREATE INDEX ix_constituent_relationship_person2 ON constituent_relationship (person2_id);


/* -----------------------------------------------------------------------------
   TABLE COMMENTS (visible via \dt+ in psql and in most GUI data dictionaries)
   ----------------------------------------------------------------------------- */
COMMENT ON TABLE designation              IS 'Lookup: one row per fund/designation.';
COMMENT ON TABLE constituent              IS 'Hub: one row per person (P) or organization (C).';
COMMENT ON TABLE contribution             IS 'Fact: one row per gift, pledge, matching gift, or bequest expectancy.';
COMMENT ON TABLE contact_preference       IS 'One row per contact restriction; drives mailable/emailable logic.';
COMMENT ON TABLE constituent_relationship IS 'Self-referencing M:N on constituent; one row per related pair, canonical order.';

